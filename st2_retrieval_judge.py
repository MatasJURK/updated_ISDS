# CONFIG

BASE_OUTPUT_DIR = "./Generation_Output"
DATE_FROM       = "2025-03-01"
DATE_TO         = "2025-03-31"
CHIMNEY         = None                          # None = both KGF1 and KGF2

LLM_BASE_URL    = "https://llmproxy.uva.nl/v1"
LLM_API_KEY     = open("./Data/API.txt").readline().strip()

# Model config 
JUDGE_MODEL     = "gpt-5.1"
MAX_TOKENS      = 3000           # approximate
TEMPERATURE     = 0

# Retry / rate-limit config 
SLEEP_BETWEEN_CALLS = 2          # seconds between API calls
MAX_RETRIES         = 3          # retries on 429 / 504

VARIANTS = ["VariantA", "VariantB", "VariantC", "VariantD"]

