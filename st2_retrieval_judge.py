# HELPERS

def extract_paragraph_from_prompt(user_input: str) -> str:
    """Extract the natural-language event paragraph from the saved prompt string."""
    m = re.search(
        r"---\s*Natural language summary\s*---\s*(.*?)\s*---\s*Structured data",
        user_input,
        re.DOTALL | re.IGNORECASE,
    )
    return m.group(1).strip() if m else ""


def format_permit_contexts(retrieved_ids: list, retrieved_contexts: list) -> str:
    """Format retrieved permit chunks with their IDs for the judge prompt."""
    lines = []
    for rid, ctx in zip(retrieved_ids, retrieved_contexts):
        lines.append(f"[{rid}]\n{ctx[:600]}")   # cap at 600 chars per chunk
    return "\n\n---\n\n".join(lines)


def json_safe(obj):
    if hasattr(obj, "item"):
        val = obj.item()
        return None if (isinstance(val, float) and math.isnan(val)) else val
    if isinstance(obj, float) and math.isnan(obj):
        return None
    raise TypeError(f"Not serialisable: {type(obj)}")

# RUBRIC PROMPT

SYSTEM_PROMPT = """\
You are an expert evaluator assessing AI-generated compliance reports for
environmental permit enforcement. Each report was generated by an LLM given:
  (a) a natural-language summary of an industrial emission event, and
  (b) a set of retrieved Dutch environmental permit conditions (voorschriften).

Your task is to score the report on four dimensions using the rubric below.
You MUST return ONLY valid JSON — no preamble, no markdown fences.
"""

RUBRIC = """\
Score each dimension 1, 2, or 3:
  1 = Absent or clearly incorrect
  2 = Partially present or incomplete
  3 = Fully present and correct

DIMENSION 1 — legal_grounding
Does every compliance claim in sections 3 and 4 cite a specific voorschrift
that exists in the RETRIEVED PERMIT CONDITIONS provided below?
Penalise if:
  - a voorschrift is cited that is NOT in the retrieved set
  - a voorschrift is cited that applies to the WRONG chimney
    (e.g. citing a KGF2-specific condition for a KGF1 event)
  - compliance conclusions are stated without any permit citation

DIMENSION 2 — evidence_integration
Are the AQ sensor readings, atmospheric conditions (wind, PG class),
and citizen report data used to support or qualify the legal observations
in sections 3 and 4? Or are they only listed in section 2 without connecting
to the permit reasoning?
Penalise if:
  - evidence is listed in section 2 but never referenced in sections 3-4
  - permit citations appear with no connection to the observed evidence
  - the report treats evidence and permit conditions as two separate topics

DIMENSION 3 — epistemic_calibration
Does the report correctly acknowledge that ambient sensor readings (µg/m³
at 1-4 km distance) cannot be directly compared to stack emission limits
(mg/Nm³ at source)? Does it hedge appropriately rather than claiming
compliance or non-compliance from ambient data alone?
Penalise if:
  - the report claims a permit limit is exceeded based only on ambient data
  - the report claims compliance is demonstrated from ambient data
  - the metric gap is not mentioned at all

DIMENSION 4 — data_gap_identification
Does section 5 correctly identify the specific evidence that would be
needed to make a formal compliance determination (e.g. stack measurements,
continuous emission monitoring data, enforcement compound measurements)?
Penalise if:
  - data gaps are vague ("more information needed") without specifying what
  - gaps relevant to the specific retrieved voorschriften are missed
  - the section is absent or only one line
"""

def build_judge_prompt(event: dict) -> str:
    """Build the full judge prompt for a single event report."""
    paragraph   = extract_paragraph_from_prompt(event.get("user_input", ""))
    permit_ctx  = format_permit_contexts(
        event.get("retrieved_ids",      []),
        event.get("retrieved_contexts", []),
    )
    chimney     = event.get("chimney", "unknown")
    dt          = event.get("event_datetime", "unknown")

    return f"""\
=== EVENT CONTEXT ===
Chimney   : {chimney}
Timestamp : {dt}
Event paragraph:
{paragraph}

=== RETRIEVED PERMIT CONDITIONS ===
{permit_ctx}

=== GENERATED REPORT TO EVALUATE ===
{event.get("llm_report", "")}

=== SCORING RUBRIC ===
{RUBRIC}

=== INSTRUCTIONS ===
Return ONLY a JSON object with this exact structure:
{{
  "legal_grounding":         {{"score": <1|2|3>, "justification": "<one sentence>"}},
  "evidence_integration":    {{"score": <1|2|3>, "justification": "<one sentence>"}},
  "epistemic_calibration":   {{"score": <1|2|3>, "justification": "<one sentence>"}},
  "data_gap_identification": {{"score": <1|2|3>, "justification": "<one sentence>"}},
  "chimney_mismatch_flag":   <true|false>,
  "chimney_mismatch_note":   "<which voorschriften cited are wrong chimney, or empty string>"
}}

chimney_mismatch_flag should be true ONLY if a cited voorschrift applies
EXCLUSIVELY to the wrong facility — meaning its emission point codes
(EL.XXX or AV.XXX) refer solely to the other plant with NO coverage of
the event chimney.

Do NOT flag as a mismatch:
- Voorschriften covering BOTH KGF1 and KGF2 in the same document
  (e.g. a tabel 1 / tabel 2 structure, or a condition listing both
  EL.107 and EL.216 emission points across the two facilities)
- Voorschriften with no emission point codes that apply generically

chimney_mismatch_note should list ONLY exclusively wrong-chimney
voorschriften — omit shared conditions entirely.
Do not include any text outside the JSON object.
"""

# SCORING

def score_event(client: OpenAI, event: dict, dry_run: bool = False) -> dict | None:
    prompt = build_judge_prompt(event)

    if dry_run:
        print("\n" + "=" * 70)
        print("DRY RUN — JUDGE PROMPT FOR EVENT", event.get("event_idx"))
        print("=" * 70)
        print(prompt[:3000])
        print("... [truncated for dry run]")
        print("=" * 70)
        return {
            "legal_grounding":         {"score": 0, "justification": "DRY RUN"},
            "evidence_integration":    {"score": 0, "justification": "DRY RUN"},
            "epistemic_calibration":   {"score": 0, "justification": "DRY RUN"},
            "data_gap_identification": {"score": 0, "justification": "DRY RUN"},
            "chimney_mismatch_flag":   False,
            "chimney_mismatch_note":   "DRY RUN",
            "_dry_run": True,
        }

    last_error = None
    for attempt in range(MAX_RETRIES + 1):
        try:
            response = client.chat.completions.create(
                model=JUDGE_MODEL,
                max_tokens=MAX_TOKENS,
                temperature=TEMPERATURE,
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user",   "content": prompt},
                ],
            )
            content = response.choices[0].message.content
            if content is None:
                _fr  = getattr(response.choices[0], 'finish_reason', 'unknown')
                _ref = getattr(response.choices[0].message, 'refusal', None)
                raise ValueError(
                    f"Model returned null content — "
                    f"finish_reason='{_fr}', refusal='{_ref}'"
                )
            raw = content.strip()

            # Strip markdown fences if the model adds them despite instructions
            raw = re.sub(r"^```(?:json)?\s*", "", raw)
            raw = re.sub(r"\s*```$",          "", raw)

            parsed = json.loads(raw)

            # Validate structure
            required = {
                "legal_grounding", "evidence_integration",
                "epistemic_calibration", "data_gap_identification",
            }
            if not required.issubset(parsed.keys()):
                raise ValueError(f"Missing keys: {required - set(parsed.keys())}")

            for dim in required:
                if "score" not in parsed[dim]:
                    raise ValueError(f"Missing score in {dim}")
                s = parsed[dim]["score"]
                if s not in (1, 2, 3):
                    raise ValueError(f"Invalid score {s} in {dim}")

            # Compute total
            parsed["total"] = sum(parsed[dim]["score"] for dim in required)
            return parsed

        except json.JSONDecodeError as e:
            last_error = f"JSON parse error: {e} | raw: {raw[:200]}"
        except ValueError as e:
            last_error = f"Validation error: {e}"
        except Exception as e:
            last_error = f"API error: {str(e)[:200]}"

        if attempt < MAX_RETRIES:
            log.warning(
                f"  Event {event.get('event_idx')} attempt {attempt+1} failed: "
                f"{last_error} — retrying in {SLEEP_BETWEEN_CALLS * 2}s"
            )
            time.sleep(SLEEP_BETWEEN_CALLS * 2)

    log.error(
        f"  Event {event.get('event_idx')} failed after {MAX_RETRIES+1} attempts: "
        f"{last_error}"
    )
    return None

# AGGREGATE HELPERS

DIMENSIONS = [
    "legal_grounding",
    "evidence_integration",
    "epistemic_calibration",
    "data_gap_identification",
]

def compute_aggregate(scored_events: list) -> dict:
    """Compute mean and std per dimension and total from scored event list."""
    import statistics

    agg = {}
    totals = []

    for dim in DIMENSIONS:
        scores = [
            e["judge_scores"][dim]["score"]
            for e in scored_events
            if e.get("judge_scores") and e["judge_scores"].get(dim)
        ]
        if scores:
            mean = sum(scores) / len(scores)
            std  = statistics.stdev(scores) if len(scores) > 1 else 0.0
            agg[dim] = {"mean": round(mean, 4), "std": round(std, 4), "n": len(scores)}
        else:
            agg[dim] = {"mean": None, "std": None, "n": 0}

    totals = [
        e["judge_scores"]["total"]
        for e in scored_events
        if e.get("judge_scores") and "total" in e["judge_scores"]
    ]
    if totals:
        agg["total"] = {
            "mean": round(sum(totals) / len(totals), 4),
            "std":  round(statistics.stdev(totals) if len(totals) > 1 else 0.0, 4),
            "min":  min(totals),
            "max":  max(totals),
            "n":    len(totals),
        }

    mismatch_count = sum(
        1 for e in scored_events
        if e.get("judge_scores", {}).get("chimney_mismatch_flag", False)
    )
    agg["chimney_mismatch_count"] = mismatch_count
    agg["chimney_mismatch_rate"]  = round(
        mismatch_count / len(scored_events), 4
    ) if scored_events else None

    return agg

# VARIANT RUNNER

def run_judge_for_variant(
    variant_name: str,
    client: OpenAI,
    dry_run: bool = False,
    limit: int | None = None,
) -> dict:
    period_slug  = f"{DATE_FROM}_to_{DATE_TO}" + (f"_{CHIMNEY}" if CHIMNEY else "")
    output_dir   = Path(BASE_OUTPUT_DIR) / variant_name
    reports_path = output_dir / f"event_reports_{period_slug}.json"

    log.info(f"\n{'='*70}")
    log.info(f"LLM JUDGE — {variant_name}")
    log.info(f"Reports: {reports_path}")
    log.info(f"Judge model: {JUDGE_MODEL} | dry_run={dry_run} | limit={limit}")
    log.info(f"{'='*70}")

    if not reports_path.exists():
        log.error(f"  Not found: {reports_path}")
        return {"variant": variant_name, "error": "event_reports not found"}

    with open(reports_path, encoding="utf-8") as f:
        all_reports = json.load(f)

    if CHIMNEY:
        all_reports = [r for r in all_reports if r.get("chimney") == CHIMNEY]

    if limit:
        all_reports = all_reports[:limit]

    log.info(f"  Loaded {len(all_reports)} event reports to score.")

    scored_events = []
    failed        = 0

    for i, event in enumerate(all_reports):
        eid = event.get("event_idx", i)
        log.info(
            f"  [{variant_name}] Event {i+1}/{len(all_reports)} "
            f"(idx={eid}, chimney={event.get('chimney')})"
        )

        result = score_event(client, event, dry_run=dry_run)

        entry = {
            "event_idx":      eid,
            "chimney":        event.get("chimney"),
            "event_datetime": event.get("event_datetime"),
            "judge_scores":   result,
        }

        if result is None:
            failed += 1
            log.warning(f"  [{variant_name}] Event {eid} — scoring failed, null result")
        elif not result.get("_dry_run"):
            total = result.get("total", "?")
            mismatch = "⚠ chimney mismatch" if result.get("chimney_mismatch_flag") else ""
            log.info(
                f"  [{variant_name}] Event {eid} — total={total}/12 "
                f"| LG={result['legal_grounding']['score']} "
                f"EI={result['evidence_integration']['score']} "
                f"EC={result['epistemic_calibration']['score']} "
                f"DG={result['data_gap_identification']['score']} "
                f"{mismatch}"
            )

        scored_events.append(entry)

        if not dry_run and i < len(all_reports) - 1:
            time.sleep(SLEEP_BETWEEN_CALLS)

    aggregate = compute_aggregate(
        [e for e in scored_events if e.get("judge_scores")]
    )

    log.info(f"\n  [{variant_name}] Summary:")
    log.info(f"    Scored: {len(scored_events) - failed}/{len(scored_events)}")
    if not dry_run and aggregate.get("total"):
        t = aggregate["total"]
        log.info(
            f"    Total score: mean={t['mean']:.2f} ± {t['std']:.2f} "
            f"(min={t['min']}, max={t['max']})"
        )
        for dim in DIMENSIONS:
            d = aggregate[dim]
            log.info(f"    {dim:<28}: mean={d['mean']:.2f} ± {d['std']:.2f}")
        log.info(
            f"    Chimney mismatches: {aggregate['chimney_mismatch_count']} "
            f"({aggregate['chimney_mismatch_rate']:.1%})"
        )

    output = {
        "variant":      variant_name,
        "judge_model":  JUDGE_MODEL,
        "period":       f"{DATE_FROM} to {DATE_TO}",
        "n_scored":     len(scored_events) - failed,
        "n_failed":     failed,
        "dry_run":      dry_run,
        "aggregate":    aggregate,
        "per_event":    scored_events,
    }

    if not dry_run:
        out_path = output_dir / f"judge_results_{period_slug}.json"
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(output, f, ensure_ascii=False, indent=2, default=json_safe)
        log.info(f"  Saved → {out_path}")

    return output

# MAIN

def main():
    parser = argparse.ArgumentParser(description="LLM-as-judge for compliance reports")
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print prompt for first event of each variant, no API calls",
    )
    parser.add_argument(
        "--variant", type=str, default=None,
        help="Score only this variant (VariantA / VariantB / VariantC)",
    )
    parser.add_argument(
        "--limit", type=int, default=None,
        help="Score only the first N events per variant (for testing)",
    )
    args = parser.parse_args()

    variants_to_run = [args.variant] if args.variant else VARIANTS

    log.info("=" * 70)
    log.info("LLM-as-judge evaluation")
    log.info(f"Judge model : {JUDGE_MODEL}")
    log.info(f"Variants    : {variants_to_run}")
    log.info(f"Period      : {DATE_FROM} to {DATE_TO}")
    log.info(f"Dry run     : {args.dry_run}")
    log.info(f"Limit       : {args.limit}")
    log.info("=" * 70)

    client = OpenAI(base_url=LLM_BASE_URL, api_key=LLM_API_KEY)

    all_results   = {}
    summary_rows  = []

    for variant_name in variants_to_run:
        try:
            result = run_judge_for_variant(
                variant_name=variant_name,
                client=client,
                dry_run=args.dry_run,
                limit=args.limit,
            )
            all_results[variant_name] = result

            if not args.dry_run and "aggregate" in result:
                agg = result["aggregate"]
                summary_rows.append({
                    "variant":               variant_name,
                    "n_scored":              result["n_scored"],
                    "total_mean":            agg.get("total", {}).get("mean"),
                    "total_std":             agg.get("total", {}).get("std"),
                    "legal_grounding":       agg.get("legal_grounding",       {}).get("mean"),
                    "evidence_integration":  agg.get("evidence_integration",  {}).get("mean"),
                    "epistemic_calibration": agg.get("epistemic_calibration", {}).get("mean"),
                    "data_gap_id":           agg.get("data_gap_identification",{}).get("mean"),
                    "chimney_mismatch_rate": agg.get("chimney_mismatch_rate"),
                })

        except Exception as e:
            log.error(f"[{variant_name}] Failed: {e}\n{traceback.format_exc()}")

    # Final summary table 
    if summary_rows:
        log.info("\n" + "=" * 90)
        log.info("FINAL JUDGE SUMMARY")
        log.info("=" * 90)
        log.info(
            f"  {'Variant':<12} {'N':>5} {'Total/12':>9} "
            f"{'LG':>6} {'EI':>6} {'EC':>6} {'DG':>6} {'Mismatch%':>10}"
        )
        log.info("  " + "-" * 90)
        for r in summary_rows:
            total = f"{r['total_mean']:.2f}±{r['total_std']:.2f}" if r["total_mean"] else "N/A"
            mm    = f"{r['chimney_mismatch_rate']:.1%}" if r["chimney_mismatch_rate"] is not None else "N/A"
            log.info(
                f"  {r['variant']:<12} {r['n_scored']:>5} {total:>9} "
                f"{r['legal_grounding'] or 0:>6.2f} "
                f"{r['evidence_integration'] or 0:>6.2f} "
                f"{r['epistemic_calibration'] or 0:>6.2f} "
                f"{r['data_gap_id'] or 0:>6.2f} "
                f"{mm:>10}"
            )

    # Save master comparison
    if not args.dry_run and summary_rows:
        period_slug  = f"{DATE_FROM}_to_{DATE_TO}" + (f"_{CHIMNEY}" if CHIMNEY else "")
        master_path  = Path(BASE_OUTPUT_DIR) / f"judge_comparison_{period_slug}.json"
        with open(master_path, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "judge_model":  JUDGE_MODEL,
                    "period":       f"{DATE_FROM} to {DATE_TO}",
                    "summary":      summary_rows,
                    "variants":     all_results,
                },
                f, ensure_ascii=False, indent=2, default=json_safe,
            )
        log.info(f"\nMaster comparison saved → {master_path}")

    log.info("All done.")


if __name__ == "__main__":
    main()
