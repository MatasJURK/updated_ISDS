"""
Rubric dimensions (each scored 1–3):
  1. legal_grounding        — every compliance claim cites a retrieved voorschrift;
                              no phantom IDs; voorschriften match the correct chimney
  2. evidence_integration   — AQ signals, atmospheric context, and citizen evidence
                              are connected to legal reasoning, not just listed
  3. epistemic_calibration  — report correctly hedges on ambient-vs-stack gap;
                              no overclaiming compliance or non-compliance
  4. data_gap_identification — report correctly identifies what specific evidence
                              is needed for a formal compliance determination

Score meanings:
  1 = Absent or incorrect
  2 = Partial / present but incomplete
  3 = Fully present and correct
"""

import os
import re
import json
import time
import logging
import argparse
from pathlib import Path
from openai import OpenAI


# CONFIG

DATE_FROM = "2025-03-01"
DATE_TO   = "2025-03-31"
PERIOD_SLUG = f"{DATE_FROM}_to_{DATE_TO}"

BASE_OUTPUT_DIR      = "./Generation_Output"
SUB3_DIR             = "./Generation_Output/Sub3Ablation"
VARIANT_D_DIR        = "./Generation_Output/VariantD"

LLM_BASE_URL = "https://llmproxy.uva.nl/v1"
LLM_API_KEY  = open("./Data/API.txt").readline().strip()

JUDGE_MODEL  = "gpt-5.1"
MAX_TOKENS   = 2000
TEMPERATURE  = 0

SLEEP_BETWEEN_CALLS = 3
MAX_RETRIES         = 3

# LOGGING

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[
        logging.FileHandler("run_sub3_judge.log", encoding="utf-8"),
        logging.StreamHandler(),
    ],
)
log = logging.getLogger(__name__)

# REPORT LOADING

def load_period_reports() -> dict:
    """
    Load all four period reports. Returns dict keyed by condition name.
    Raises FileNotFoundError with a clear message if any report is missing.
    """
    reports = {}

    # Baseline VariantD
    baseline_path = Path(VARIANT_D_DIR) / f"period_report_{PERIOD_SLUG}.txt"
    if not baseline_path.exists():
        raise FileNotFoundError(
            f"Baseline VariantD period report not found: {baseline_path}\n"
            f"Make sure your VariantD output is in {VARIANT_D_DIR}"
        )
    reports["baseline"] = baseline_path.read_text(encoding="utf-8")
    log.info(f"  Loaded baseline ({len(reports['baseline'])} chars): {baseline_path}")

    # Ablated conditions
    for condition in ["no_aq", "no_citizen", "no_weather"]:
        path = Path(SUB3_DIR) / f"period_report_{condition}_{PERIOD_SLUG}.txt"
        if not path.exists():
            raise FileNotFoundError(
                f"Ablated period report not found: {path}\n"
                f"Run run_sub3_ablation.py first."
            )
        reports[condition] = path.read_text(encoding="utf-8")
        log.info(f"  Loaded {condition} ({len(reports[condition])} chars): {path}")

    return reports

# JUDGE PROMPTS

SYSTEM_PROMPT = """\
You are an expert evaluator assessing AI-generated compliance reports for
environmental permit enforcement at an industrial site (Tata Steel IJmuiden,
coke oven chimneys KGF1 and KGF2, overseen by OD NZKG).

Each report was generated by an LLM given a set of per-event compliance
mini-reports and retrieved Dutch environmental permit conditions (voorschriften).

Your task is to score the period-level report on four dimensions.
You MUST return ONLY valid JSON — no preamble, no markdown fences.
"""

RUBRIC = """\
Score each dimension 1, 2, or 3:
  1 = Absent or clearly incorrect
  2 = Partially present or incomplete
  3 = Fully present and correct

DIMENSION 1 — legal_grounding
Are compliance concerns in sections 2 and 4 tied to specific voorschrift
numbers (e.g. 1.2.20.H, I., III) rather than vague references?
Penalise if:
  - conclusions reference "permit conditions" without citing specific IDs
  - cited IDs cannot plausibly exist in a Dutch industrial air permit
  - section 4 recommendation has no permit-level justification

DIMENSION 2 — evidence_integration
Is the available evidence (AQ readings, citizen complaints, atmospheric
context) used to support or qualify the legal observations in sections
3 and 4? Or is evidence only listed in section 1/3 without connecting
to permit reasoning?
Penalise if:
  - evidence and permit sections are completely disconnected
  - section 4 recommendation ignores the evidence discussed earlier
  - the report notes data absence but makes no connection between
    missing evidence and the specific permit conditions it affects

DIMENSION 3 — epistemic_calibration
Does the report correctly acknowledge that ambient sensor readings
(µg/m³ at 1-4 km distance) cannot be directly compared to stack
emission limits (mg/Nm³ at source)? Does it hedge appropriately?
Penalise if:
  - the report claims a permit limit is exceeded based only on ambient data
  - the metric gap between ambient and stack measurements is not acknowledged
  - data absence is acknowledged but the report still draws firm
    compliance/non-compliance conclusions

DIMENSION 4 — data_gap_identification
Does section 5 correctly identify the specific evidence that would be
needed to make a formal compliance determination?
Penalise if:
  - gaps are vague ("more information needed") without specifying what
  - the section fails to connect missing data to specific voorschriften
  - the ablated modality's absence is not acknowledged as a limitation
    (e.g. a no_aq report should flag AQ data as a missing evidence type)
"""

CONDITION_CONTEXT = {
    "baseline": (
        "This report was generated with FULL evidence: AQ sensor readings, "
        "citizen complaints, and atmospheric dispersion context were all available."
    ),
    "no_aq": (
        "This report was generated WITHOUT air quality sensor data. "
        "AQ z-scores, pollutant concentrations, and fingerprint group readings "
        "were systematically removed before generation."
    ),
    "no_citizen": (
        "This report was generated WITHOUT citizen complaint data. "
        "All community reports, odour descriptors, and postcode impact information "
        "were systematically removed before generation."
    ),
    "no_weather": (
        "This report was generated WITHOUT atmospheric context. "
        "Wind direction/speed, Pasquill-Gifford stability class, plume direction, "
        "offshore flags, and concurrent event attribution were removed."
    ),
}


def build_judge_prompt(condition: str, report_text: str) -> str:
    return f"""\
=== ASSESSMENT CONTEXT ===
This is a period-level compliance assessment covering {DATE_FROM} to {DATE_TO}
for emission events at Tata Steel IJmuiden KGF1/KGF2 coke oven chimneys.

Evidence availability note:
{CONDITION_CONTEXT[condition]}

=== PERIOD REPORT TO EVALUATE ===
{report_text}

=== SCORING RUBRIC ===
{RUBRIC}

=== INSTRUCTIONS ===
Return ONLY a JSON object with this exact structure:
{{
  "legal_grounding":         {{"score": <1|2|3>, "justification": "<one sentence>"}},
  "evidence_integration":    {{"score": <1|2|3>, "justification": "<one sentence>"}},
  "epistemic_calibration":   {{"score": <1|2|3>, "justification": "<one sentence>"}},
  "data_gap_identification": {{"score": <1|2|3>, "justification": "<one sentence>"}}
}}

Do not include any text outside the JSON object.
"""

# SCORING

DIMENSIONS = [
    "legal_grounding",
    "evidence_integration",
    "epistemic_calibration",
    "data_gap_identification",
]


def score_report(
    client: OpenAI,
    condition: str,
    report_text: str,
    dry_run: bool = False,
) -> dict | None:
    prompt = build_judge_prompt(condition, report_text)

    if dry_run:
        print(f"\n{'='*70}")
        print(f"DRY RUN — JUDGE PROMPT FOR: {condition}")
        print(f"{'='*70}")
        print(prompt[:2000])
        print("... [truncated]")
        return {dim: {"score": 0, "justification": "DRY RUN"} for dim in DIMENSIONS}

    last_error = None
    for attempt in range(MAX_RETRIES + 1):
        try:
            response = client.chat.completions.create(
                model=JUDGE_MODEL,
                max_tokens=MAX_TOKENS,
                temperature=TEMPERATURE,
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user",   "content": prompt},
                ],
            )
            raw = response.choices[0].message.content.strip()
            raw = re.sub(r"^```(?:json)?\s*", "", raw)
            raw = re.sub(r"\s*```$",          "", raw)

            parsed = json.loads(raw)

            required = set(DIMENSIONS)
            if not required.issubset(parsed.keys()):
                raise ValueError(f"Missing keys: {required - set(parsed.keys())}")
            for dim in required:
                if "score" not in parsed[dim]:
                    raise ValueError(f"Missing score in {dim}")
                s = parsed[dim]["score"]
                if s not in (1, 2, 3):
                    raise ValueError(f"Invalid score {s} in {dim}")

            parsed["total"] = sum(parsed[dim]["score"] for dim in DIMENSIONS)
            return parsed

        except json.JSONDecodeError as e:
            last_error = f"JSON parse error: {e}"
        except ValueError as e:
            last_error = f"Validation error: {e}"
        except Exception as e:
            last_error = f"API error: {str(e)[:200]}"

        if attempt < MAX_RETRIES:
            log.warning(
                f"  [{condition}] attempt {attempt+1} failed: {last_error} "
                f"— retrying in {SLEEP_BETWEEN_CALLS * 2}s"
            )
            time.sleep(SLEEP_BETWEEN_CALLS * 2)

    log.error(f"  [{condition}] failed after {MAX_RETRIES+1} attempts: {last_error}")
    return None

# MAIN

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    log.info("=" * 70)
    log.info("Sub-RQ 3 — LLM-as-judge period report scoring")
    log.info(f"Judge model : {JUDGE_MODEL}")
    log.info(f"Period      : {DATE_FROM} to {DATE_TO}")
    log.info(f"Dry run     : {args.dry_run}")
    log.info("=" * 70)

    # Load reports
    log.info("Loading period reports...")
    try:
        reports = load_period_reports()
    except FileNotFoundError as e:
        log.error(str(e))
        return

    client = OpenAI(base_url=LLM_BASE_URL, api_key=LLM_API_KEY)

    conditions = ["baseline", "no_aq", "no_citizen", "no_weather"]
    results    = {}

    for condition in conditions:
        log.info(f"\nScoring: {condition}")
        scores = score_report(
            client,
            condition,
            reports[condition],
            dry_run=args.dry_run,
        )
        results[condition] = {
            "condition": condition,
            "scores":    scores,
        }
        if scores and not args.dry_run:
            total = scores.get("total", "?")
            log.info(
                f"  {condition}: total={total}/12 | "
                f"LG={scores['legal_grounding']['score']} "
                f"EI={scores['evidence_integration']['score']} "
                f"EC={scores['epistemic_calibration']['score']} "
                f"DG={scores['data_gap_identification']['score']}"
            )
        if not args.dry_run:
            time.sleep(SLEEP_BETWEEN_CALLS)

    # Summary table
    if not args.dry_run:
        log.info("\n" + "=" * 70)
        log.info("SUB-RQ 3 JUDGE — SUMMARY")
        log.info("=" * 70)
        log.info(
            f"  {'Condition':<14} {'Total/12':>9} "
            f"{'LG':>5} {'EI':>5} {'EC':>5} {'DG':>5}"
        )
        log.info("  " + "-" * 50)
        for condition in conditions:
            s = results[condition].get("scores")
            if s and "total" in s:
                log.info(
                    f"  {condition:<14} {s['total']:>9} "
                    f"{s['legal_grounding']['score']:>5} "
                    f"{s['evidence_integration']['score']:>5} "
                    f"{s['epistemic_calibration']['score']:>5} "
                    f"{s['data_gap_identification']['score']:>5}"
                )
            else:
                log.info(f"  {condition:<14} FAILED")

    # Save output
    if not args.dry_run:
        out_dir  = Path(SUB3_DIR)
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = out_dir / f"sub3_judge_results_{PERIOD_SLUG}.json"
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(
                {
                    "judge_model": JUDGE_MODEL,
                    "period":      f"{DATE_FROM} to {DATE_TO}",
                    "conditions":  results,
                },
                f, ensure_ascii=False, indent=2,
            )
        log.info(f"\nResults saved → {out_path}")

    log.info("Done.")


if __name__ == "__main__":
    main()
